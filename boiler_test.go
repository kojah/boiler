package boiler_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kojah/boiler"
)

const source = `package p

type Item struct {
	Name  string
	Tags  []string
	inner *Item
}
`

// module writes a one-package module and a configuration with one snapshot
// of Item whose field rules are given; it returns the config path.
func module(t *testing.T, fields string) string {
	t.Helper()
	root := t.TempDir()
	write(t, filepath.Join(root, "go.mod"), "module example.com/m\n\ngo 1.24\n")
	write(t, filepath.Join(root, "p", "p.go"), source)
	if err := os.CopyFS(filepath.Join(root, "recipes", "snapshot"), os.DirFS("recipes/snapshot")); err != nil {
		t.Fatal(err)
	}
	config := "recipe snapshot = \"recipes/snapshot\"\noutput \"p/boiler_items_gen.go\" {\n" +
		"snapshot snapshotItem(Item) {\n" + fields + "}\n}\n"

	path := filepath.Join(root, "generate.boiler")
	write(t, path, config)
	return path
}

func write(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestFieldCoverage checks the tool's central contract: every field needs
// exactly one valid rule before anything is generated.
func TestFieldCoverage(t *testing.T) {
	for _, test := range []struct {
		name, fields, want string
	}{
		{"missing", "          Name = keep\n          Tags = clone\n", "field inner has no rule"},
		{"unknown", "          Name = keep\n          Tags = clone\n          inner = keep\n          Size = keep\n", "unknown fields: Size"},
		{"misapplied", "          Name = clone\n          Tags = clone\n          inner = keep\n", "clone needs a slice or map"},
		{"shape", "          Name = keep\n          Tags = clone\n          inner = each(keep)\n", "each needs a slice or map"},
		{"grammar", "          Name = keep\n          Tags = each(clone\n          inner = keep\n", "expected , or )"},
	} {
		t.Run(test.name, func(t *testing.T) {
			config, err := boiler.Load(module(t, test.fields))
			if err == nil {
				_, err = config.Compile("")
			}

			if err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("Compile error %v, want %q", err, test.want)
			}
		})
	}
}

// TestPublish checks freshness reporting, generation, obsolete removal and
// the refusal to overwrite hand-written files.
func TestPublish(t *testing.T) {
	path := module(t, "          Name = keep\n          Tags = clone\n          inner = keep\n")
	config, err := boiler.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	artifacts, err := config.Compile("")
	if err != nil {
		t.Fatal(err)
	}
	if err := config.Publish(artifacts, true); err == nil || !strings.Contains(err.Error(), "missing p/boiler_items_gen.go") {
		t.Fatalf("check before generation: %v", err)
	}
	obsolete := filepath.Join(filepath.Dir(path), "p", "boiler_old_gen.go")
	write(t, obsolete, "// Code generated by boiler; DO NOT EDIT.\n\npackage p\n")
	if err := config.Publish(artifacts, false); err != nil {
		t.Fatal(err)
	}
	if err := config.Publish(artifacts, true); err != nil {
		t.Fatalf("check after generation: %v", err)
	}
	if _, err := os.Stat(obsolete); !os.IsNotExist(err) {
		t.Fatalf("obsolete output survived: %v", err)
	}
	generated, err := os.ReadFile(artifacts[0].Path)
	if err != nil || !strings.Contains(string(generated), "out.Tags = slices.Clone(out.Tags)") {
		t.Fatalf("generated snapshot does not clone Tags:\n%s", generated)
	}
	write(t, artifacts[0].Path, "package p\n")
	if err := config.Publish(artifacts, false); err == nil || !strings.Contains(err.Error(), "refusing to overwrite") {
		t.Fatalf("overwrote a hand-written file: %v", err)
	}
}
