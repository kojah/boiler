package boiler

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"path/filepath"
	"sort"
	"strings"
)

// header is the standard generated-code marker; tools and the repository's
// file budgets recognize it.
const header = "// Code generated by boiler; DO NOT EDIT.\n"

// Artifact is one rendered file. Path is absolute; Data is deterministic.
type Artifact struct {
	Output string
	Path   string
	Data   []byte
}

// Compile renders the selected output, or every output when name is empty.
// It writes nothing. Errors name the output, target and field at fault.
func (c *Config) Compile(name string) ([]Artifact, error) {
	l := newLoader(c.moduleRoot, c.module)
	var artifacts []Artifact
	for _, t := range c.Outputs {
		if name != "" && t.Out != name {
			continue
		}
		data, err := c.compileOutput(l, t)
		if err != nil {
			return nil, fmt.Errorf("output %s: %w", t.Out, err)
		}
		artifacts = append(artifacts, Artifact{Output: t.Out, Path: filepath.Join(c.root, t.Out), Data: data})
	}
	if name != "" && len(artifacts) == 0 {
		return nil, fmt.Errorf("unknown output %q", name)
	}
	return artifacts, nil
}

// unit accumulates one generated file.
type unit struct {
	config    *Config
	loader    *loader
	pkg       *source
	name      string
	imports   map[string]string
	body      bytes.Buffer
	targets   []Target
	allocated map[string]bool
}

func (c *Config) compileOutput(l *loader, output Output) ([]byte, error) {
	pkg, err := l.load(filepath.Join(c.root, output.Package))
	if err != nil {
		return nil, err
	}
	if len(pkg.files) == 0 {
		return nil, fmt.Errorf("package %s has no Go files", output.Package)
	}
	u := &unit{config: c, loader: l, pkg: pkg, name: pkg.files[0].Name.Name, imports: map[string]string{}, targets: output.Targets, allocated: map[string]bool{}}
	for _, target := range output.Targets {
		if err := u.expand(target); err != nil {
			return nil, fmt.Errorf("target %s: %w", target.Name, err)
		}
	}
	return u.render()
}

// structOf resolves a target's struct. A qualified name reads another
// module package, whose fields must then all be exported.
func (u *unit) structOf(written string) ([]field, *source, error) {
	qualifier, name, foreign := strings.Cut(written, ".")
	if !foreign {
		fields, err := u.pkg.structFields(written)
		return fields, u.pkg, err
	}
	importPath, err := u.use(qualifier, nil)
	if err != nil {
		return nil, nil, err
	}
	src, err := u.loader.loadImport(importPath)
	if err != nil {
		return nil, nil, err
	}
	fields, err := src.structFields(name)
	if err != nil {
		return nil, nil, err
	}
	for _, f := range fields {
		if !ast.IsExported(f.name) {
			return nil, nil, fmt.Errorf("%s has unexported field %s; generate inside its package instead", written, f.name)
		}
	}
	return fields, src, nil
}

// rules checks field coverage and orders parsed rules by declaration.
// Duplicate assignments are rejected when lowering the configuration.
func rules(fields []field, written map[string]*Rule) ([]*Rule, error) {
	known := map[string]bool{}
	result := make([]*Rule, len(fields))
	for i, f := range fields {
		known[f.name] = true
		rule, ok := written[f.name]
		if !ok || rule == nil {
			return nil, fmt.Errorf("field %s has no rule", f.name)
		}
		result[i] = rule
	}
	var unknown []string
	for name := range written {
		if !known[name] {
			unknown = append(unknown, name)
		}
	}
	if len(unknown) > 0 {
		sort.Strings(unknown)
		return nil, fmt.Errorf("rules name unknown fields: %s", strings.Join(unknown, ", "))
	}
	return result, nil
}

// use records the import behind a qualifier, read from file when given and
// otherwise from any file of the target package.
func (u *unit) use(qualifier string, file *ast.File) (string, error) {
	imports := u.pkg.packageImports()
	if file != nil {
		imports = importsOf(file)
	}
	importPath := imports[qualifier]
	if importPath == "" {
		return "", fmt.Errorf("qualifier %s has no unambiguous import in package %s", qualifier, u.pkg.path)
	}
	if previous, ok := u.imports[qualifier]; ok && previous != importPath {
		return "", fmt.Errorf("qualifier %s names both %s and %s", qualifier, previous, importPath)
	}
	u.imports[qualifier] = importPath
	return importPath, nil
}

// typeText prints a field type for the generated file, importing what it uses.
func (u *unit) typeText(f field, expr ast.Expr) (string, error) {
	for _, qualifier := range qualifiers(expr) {
		if _, err := u.use(qualifier, f.file); err != nil {
			return "", err
		}
	}
	return u.loader.text(expr), nil
}

// useWritten imports the qualifiers of a type written in the configuration.
func (u *unit) useWritten(written string) error {
	expr, err := parser.ParseExpr(written)
	if err != nil {
		return fmt.Errorf("type %q: %w", written, err)
	}
	for _, qualifier := range qualifiers(expr) {
		if _, err := u.use(qualifier, nil); err != nil {
			return err
		}
	}
	return nil
}

// useImport records a standard or module import by path.
func (u *unit) useImport(importPath string) string {
	for _, name := range sortedKeys(u.imports) {
		if u.imports[name] == importPath {
			return name
		}
	}
	base := defaultName(importPath)
	name := base
	reserved := u.reservedNames()
	sourceImports := u.pkg.packageImports()
	for suffix := 2; reserved[name] && sourceImports[name] != importPath || u.imports[name] != ""; suffix++ {
		name = fmt.Sprintf("%s%d", base, suffix)
	}
	u.imports[name] = importPath
	return name
}

func (u *unit) render() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header + "\npackage " + u.name + "\n")
	if len(u.imports) > 0 {
		names := make([]string, 0, len(u.imports))
		for name := range u.imports {
			names = append(names, name)
		}
		// Standard-library imports come first, as goimports groups them.
		standard := func(name string) bool { return !strings.Contains(strings.Split(u.imports[name], "/")[0], ".") }
		sort.Slice(names, func(i, j int) bool {
			if standard(names[i]) != standard(names[j]) {
				return standard(names[i])
			}
			return u.imports[names[i]] < u.imports[names[j]]
		})
		out.WriteString("\nimport (\n")
		for i, name := range names {
			importPath := u.imports[name]
			if i > 0 && standard(names[i-1]) && !standard(name) {
				out.WriteString("\n")
			}
			if defaultName(importPath) == name {
				fmt.Fprintf(&out, "\t%q\n", importPath)
			} else {
				fmt.Fprintf(&out, "\t%s %q\n", name, importPath)
			}
		}
		out.WriteString(")\n")
	}
	out.Write(u.body.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated Go does not parse: %w\n%s", err, out.Bytes())
	}
	return formatted, nil
}
