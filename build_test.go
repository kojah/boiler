package boiler_test

import (
	"go/build"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kojah/boiler"
)

func TestOutputBuildConstraints(t *testing.T) {
	for _, expression := range []string{"contracts", "!contracts", "contracts && (linux || darwin)"} {
		t.Run(expression, func(t *testing.T) {
			path := module(t, "Name = keep\nTags = clone\ninner = keep\n")
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			write(t, path, strings.Replace(string(data), `output "p/boiler_items_gen.go" {`, `output "p/boiler_items_gen.go" build("`+expression+`") {`, 1))
			config, err := boiler.Load(path)
			if err != nil {
				t.Fatal(err)
			}
			artifacts, err := config.Compile("")
			if err != nil {
				t.Fatal(err)
			}
			if !strings.HasPrefix(string(artifacts[0].Data), "//go:build "+expression+"\n\n// Code generated by boiler;") {
				t.Fatalf("unexpected generated header: %s", artifacts[0].Data)
			}
			if err := config.Publish(artifacts, false); err != nil {
				t.Fatal(err)
			}
			if err := config.Publish(artifacts, true); err != nil {
				t.Fatal(err)
			}
			ctx := build.Default
			ctx.GOOS = "linux"
			for _, tagged := range []bool{false, true} {
				ctx.BuildTags = nil
				if tagged {
					ctx.BuildTags = []string{"contracts"}
				}
				included, err := ctx.MatchFile(filepath.Dir(artifacts[0].Path), filepath.Base(artifacts[0].Path))
				if err != nil {
					t.Fatal(err)
				}
				want := tagged
				if expression == "!contracts" {
					want = !tagged
				}
				if included != want {
					t.Fatalf("tagged=%t included=%t want=%t", tagged, included, want)
				}
			}
		})
	}
}

func TestOutputRejectsInvalidBuildConstraints(t *testing.T) {
	for _, expression := range []string{"", "contracts &&", "contracts || (linux", "contracts\\npackage forged"} {
		path := module(t, "Name = keep\nTags = clone\ninner = keep\n")
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		write(t, path, strings.Replace(string(data), `output "p/boiler_items_gen.go" {`, `output "p/boiler_items_gen.go" build("`+expression+`") {`, 1))
		if _, err := boiler.Load(path); err == nil {
			t.Fatalf("accepted invalid constraint %q", expression)
		}
	}
}
